ALTER TABLE dark ALTER COLUMN status SET NOT NULL;

-- dark.dataset_id must be ON DELETE SET NULL: destroying a dataset (including deleting a
-- never-published draft) keeps the row so its ARK can be tombstoned. The entity declares
-- ConstraintMode.NO_CONSTRAINT, so the only foreign key is this one. Drop any other FK on
-- the column (whatever its name) and create it once.
DO $$
DECLARE
    fk record;
BEGIN
    FOR fk IN
        SELECT c.conname
        FROM pg_constraint c
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
        WHERE c.conrelid = 'dark'::regclass
          AND c.contype = 'f'
          AND a.attname = 'dataset_id'
    LOOP
        EXECUTE format('ALTER TABLE dark DROP CONSTRAINT %I', fk.conname);
    END LOOP;
END
$$;

ALTER TABLE dark
    ADD CONSTRAINT fk_dark_dataset_id
    FOREIGN KEY (dataset_id) REFERENCES dvobject(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_dark_status ON dark(status);
CREATE INDEX IF NOT EXISTS idx_dark_updated_at ON dark(updated_at);
CREATE INDEX IF NOT EXISTS idx_dark_client_item_id ON dark(client_item_id);
CREATE INDEX IF NOT EXISTS idx_dark_reservation_pending ON dark(updated_at) WHERE ark IS NULL;
CREATE INDEX IF NOT EXISTS idx_dark_tombstone_pending ON dark(updated_at) WHERE tombstone_requested AND status <> 'T';
