CREATE TABLE IF NOT EXISTS dark (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id              BIGINT UNIQUE,
    -- NULL while a reservation is a durable intent not yet confirmed by the Minter.
    ark                     VARCHAR(256) UNIQUE,
    status                  CHAR(1) NOT NULL,
    client_item_id          VARCHAR(100) NOT NULL,
    target                  VARCHAR(1024),
    sent_version            VARCHAR(32),
    sent_dataset_version_id BIGINT,
    sent_revision           BIGINT,
    metadata_cid            VARCHAR(128),
    level1_cid              VARCHAR(128),
    level2_cid              VARCHAR(128),
    attempts                INTEGER NOT NULL DEFAULT 0,
    -- Consecutive automatic updatecurrent failures adding the Other ID (max 3, then manual).
    other_id_attempts       INTEGER NOT NULL DEFAULT 0,
    last_error              TEXT,
    tombstone_requested     BOOLEAN NOT NULL DEFAULT false,
    was_published           BOOLEAN NOT NULL DEFAULT false,
    reservation_token       VARCHAR(36),
    reservation_lease_until TIMESTAMP,
    row_version             BIGINT NOT NULL DEFAULT 0,
    created_at              TIMESTAMP NOT NULL DEFAULT now(),
    updated_at              TIMESTAMP NOT NULL DEFAULT now()
);

